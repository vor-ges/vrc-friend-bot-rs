#!/usr/bin/env python3
"""upstream/i18n.py の LANGS / CODES / TABLES から src/i18n_table.rs を生成する。

Python版の翻訳が変わったら upstream/ を更新して、これを再実行するだけでRust側の訳が同期する。
使い方: python3 tools/gen_i18n_table.py
"""
import importlib.util, pathlib, sys

root = pathlib.Path(__file__).resolve().parent.parent
spec = importlib.util.spec_from_file_location("py_i18n", root / "upstream" / "i18n.py")
py = importlib.util.module_from_spec(spec); spec.loader.exec_module(py)


def lit(s):
    out = ['"']
    for ch in s:
        out.append({"\\": "\\\\", '"': '\\"', "\n": "\\n", "\r": "\\r", "\t": "\\t"}.get(ch, ch))
    out.append('"')
    return "".join(out)


L = ["// @generated by tools/gen_i18n_table.py from upstream/i18n.py -- 手で編集しないこと。", ""]
L.append("pub const LANGS: &[(&str, &str)] = &[")
L += [f"    ({lit(k)}, {lit(v)})," for k, v in py.LANGS.items()]
L += ["];", "", "pub const CODES: &[(&str, &str)] = &["]
L += [f"    ({lit(k)}, {lit(v)})," for k, v in py.CODES.items()]
L += ["];", ""]
for lang, table in py.TABLES.items():
    L.append(f"pub const TABLE_{lang.upper()}: &[(&str, &str)] = &[")
    L += [f"    ({lit(k)}, {lit(v)})," for k, v in table.items()]
    L += ["];", ""]
L.append("pub fn table(lang: &str) -> Option<&'static [(&'static str, &'static str)]> {")
L.append("    match lang {")
L += [f"        {lit(lang)} => Some(TABLE_{lang.upper()})," for lang in py.TABLES]
L += ["        _ => None,", "    }", "}", ""]
(root / "src" / "i18n_table.rs").write_text("\n".join(L), encoding="utf-8")
print(f"generated {len(py.TABLES)} table(s), {sum(len(t) for t in py.TABLES.values())} entries")
